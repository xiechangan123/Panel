package openlitespeed

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"sync"

	"github.com/acepanel/panel/v3/pkg/webserver/conf"

	"github.com/acepanel/panel/v3/pkg/cert"
)

var syncMu sync.Mutex

// 默认证书，供尚无站点证书的 HTTPS 监听器握手
const (
	defaultCert = PanelConfDir + "/default.crt"
	defaultKey  = PanelConfDir + "/default.key"
)

// Sync 重建面板托管的主配置片段，这些内容无法拆到站点文件，每次保存站点或重载前整体重建
func Sync() error {
	syncMu.Lock()
	defer syncMu.Unlock()

	// 未安装时跳过
	if _, err := os.Stat(PanelConfDir); err != nil {
		return nil
	}
	if err := syncVhosts(); err != nil {
		return err
	}
	if err := syncListeners(); err != nil {
		return err
	}

	return syncPHP()
}

// syncVhosts 按站点 vhconf 生成注册块与 configFile 桩
func syncVhosts() error {
	if err := os.MkdirAll(vhostStubDir, 0700); err != nil {
		return fmt.Errorf("failed to create vhost stub directory: %w", err)
	}

	cfg := &conf.Config{}
	cfg.Append(conf.Cmt("Auto-generated by AcePanel. DO NOT EDIT MANUALLY!"))
	keep := make(map[string]bool)
	matches, _ := filepath.Glob(filepath.Join(SitesPath, "*", "config", VhostConfName))
	sort.Strings(matches)
	for _, path := range matches {
		siteDir := filepath.Dir(filepath.Dir(path))
		site := filepath.Base(siteDir)
		stub := filepath.Join(vhostStubDir, site+".conf")
		if err := os.WriteFile(stub, []byte("include "+path+"\n"), 0600); err != nil {
			return fmt.Errorf("failed to write vhost stub: %w", err)
		}
		keep[filepath.Base(stub)] = true
		b := cfg.AddBlock("virtualhost", site)
		b.Add("vhRoot", siteDir)
		b.Add("configFile", stub)
		b.Add("allowSymbolLink", "1")
		b.Add("enableScript", "1")
		b.Add("restrained", "0")
		b.Add("setUIDMode", "0")
	}

	// 清理已删除站点的桩与转储文件
	entries, _ := os.ReadDir(vhostStubDir)
	for _, entry := range entries {
		if !keep[strings.TrimSuffix(entry.Name(), ".txt")] {
			_ = os.Remove(filepath.Join(vhostStubDir, entry.Name()))
		}
	}

	if err := os.WriteFile(VhostsConf, []byte(Export(cfg)), 0600); err != nil {
		return fmt.Errorf("failed to write vhosts config: %w", err)
	}

	return nil
}

// syncListeners 汇总所有站点记录的监听地址与域名，生成 listener 块
func syncListeners() error {
	if err := ensureDefaultCert(); err != nil {
		return err
	}

	type listener struct {
		address string
		secure  bool
		maps    []string
	}
	byAddr := make(map[string]*listener)
	var order []string
	get := func(addr string) *listener {
		if l, ok := byAddr[addr]; ok {
			return l
		}
		l := &listener{address: addr}
		byAddr[addr] = l
		order = append(order, addr)
		return l
	}
	get("*:80")
	get("*:443").secure = true

	matches, _ := filepath.Glob(filepath.Join(SitesPath, "*", "config", ListenConfName))
	sort.Strings(matches)
	for _, path := range matches {
		cfg, err := ParseFile(path)
		if err != nil {
			continue
		}
		site := filepath.Base(filepath.Dir(filepath.Dir(path)))
		domains := strings.Fields(cfg.Value("domain"))
		if len(domains) == 0 {
			continue
		}
		for _, d := range cfg.GetAll("listen") {
			fields := strings.Fields(d.Arg(0))
			if len(fields) == 0 {
				continue
			}
			l := get(listenerAddress(fields[0]))
			for _, arg := range fields[1:] {
				if arg == "ssl" {
					l.secure = true
				}
			}
			l.maps = append(l.maps, site+" "+strings.Join(domains, ", "))
		}
	}

	cfg := &conf.Config{}
	cfg.Append(conf.Cmt("Auto-generated by AcePanel. DO NOT EDIT MANUALLY!"))
	for _, addr := range order {
		l := byAddr[addr]
		b := cfg.AddBlock("listener", listenerName(addr))
		b.Add("address", addr)
		if l.secure {
			b.Add("secure", "1")
			b.Add("keyFile", defaultKey)
			b.Add("certFile", defaultCert)
		} else {
			b.Add("secure", "0")
		}
		catchAll := false
		for _, m := range l.maps {
			b.Add("map", m)
			catchAll = catchAll || strings.HasSuffix(m, " *")
		}
		// 未命中站点的请求交给默认站点，每个监听器只允许一个通配映射
		if !catchAll {
			b.Add("map", "default *")
		}
	}

	if err := os.WriteFile(ListenersConf, []byte(Export(cfg)), 0600); err != nil {
		return fmt.Errorf("failed to write listeners config: %w", err)
	}

	return nil
}

func ensureDefaultCert() error {
	if _, err := os.Stat(defaultCert); err == nil {
		if _, err = os.Stat(defaultKey); err == nil {
			return nil
		}
	}
	crt, key, err := cert.GenerateSelfSigned([]string{"localhost"})
	if err != nil {
		return err
	}
	if err = os.WriteFile(defaultCert, crt, 0600); err != nil {
		return err
	}
	return os.WriteFile(defaultKey, key, 0600)
}

// listenerAddress 将站点监听地址规整为 listener 的 address
func listenerAddress(addr string) string {
	if !strings.Contains(addr, ":") {
		return "*:" + addr
	}
	if port, ok := strings.CutPrefix(addr, "0.0.0.0:"); ok {
		return "*:" + port
	}
	return addr
}

// listenerName 由地址派生唯一的 listener 名称
func listenerName(addr string) string {
	return safeName(strings.NewReplacer("*", "any", "[::]", "ip6").Replace(addr))
}
